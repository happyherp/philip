export function detectLang() {
  const raw = (navigator.language || "en").toLowerCase();
  if (raw.startsWith("es")) return "es";
  if (raw.startsWith("de")) return "de";
  return "en";
}

export function getStrings(lang) {
  return I18N[lang] || I18N.en;
}
